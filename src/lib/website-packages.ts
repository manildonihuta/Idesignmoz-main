import "server-only";

import { supabaseAdmin } from "@/lib/supabase-admin";

export type WebsitePackageFeature = {
  label: string;
  note: string | null;
  qty: number;
};

export type WebsitePackage = {
  id: string;
  name: string;
  slug: string;
  description: string | null;
  basePrice: number; // MZN, from DB
  price: number;     // effective after discount
  popular: boolean;
  features: WebsitePackageFeature[];
};

function applyDiscount(
  base: number,
  discountType: string | null,
  discountValue: number,
): number {
  const b = Number(base) || 0;
  const v = Number(discountValue) || 0;
  if (discountType === "fixed") return Math.max(0, Math.round(b - v));
  if (discountType === "percent") return Math.max(0, Math.round(b * (1 - v / 100)));
  return b;
}

export async function listWebsitePackages(): Promise<WebsitePackage[]> {
  const { data: packages, error } = await supabaseAdmin
    .from("service_packages")
    .select("*")
    .eq("active", true)
    .order("sort", { ascending: true });

  if (error || !packages?.length) return [];

  const packageIds = packages.map((p) => p.id);
  const [itemsRes, servicesRes] = await Promise.all([
    supabaseAdmin
      .from("service_package_items")
      .select("package_id, service_id, qty, note")
      .in("package_id", packageIds),
    supabaseAdmin.from("services").select("id, name"),
  ]);

  const serviceNames = new Map<string, string>();
  for (const s of servicesRes.data ?? []) {
    serviceNames.set(s.id, s.name);
  }

  const featuresByPackage = new Map<string, WebsitePackageFeature[]>();
  for (const item of itemsRes.data ?? []) {
    const key = String(item.package_id);
    const list = featuresByPackage.get(key) ?? [];
    const name = serviceNames.get(String(item.service_id));
    if (name) {
      list.push({
        label: name,
        note: typeof item.note === "string" && item.note ? item.note : null,
        qty: Number(item.qty ?? 1),
      });
    }
    featuresByPackage.set(key, list);
  }

  return packages.map((p) => ({
    id: p.id,
    name: p.name,
    slug: p.slug,
    description: p.description ?? null,
    basePrice: Number(p.base_price) || 0,
    price: applyDiscount(Number(p.base_price) || 0, p.discount_type ?? null, Number(p.discount_value) || 0),
    popular: p.popular ?? false,
    features: featuresByPackage.get(String(p.id)) ?? [],
  }));
}

export async function getWebsitePackage(slug: string): Promise<WebsitePackage | null> {
  const all = await listWebsitePackages();
  return all.find((p) => p.slug === slug) ?? null;
}